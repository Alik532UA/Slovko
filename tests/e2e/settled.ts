import type { Page } from "@playwright/test";

/**
 * Стан, у якому можна міряти: маркер видимий І жодна анімація вже не біжить.
 *
 * Клас дефекту: гейт міряє КАДР, а не стан. `toBeVisible()` справджується на
 * ПЕРШОМУ кадрі анімації входу — модалка вже в дереві й уже не прозора, — тож
 * усе, що читається одразу після нього, знято посеред переходу.
 *
 * Заміряно 2026-09-11 на зібраному сайті, по три прогони на стан. Скільки
 * анімацій ще біжить на момент видимого маркера:
 *
 *   | стан    | прогін 1 | прогін 2 | прогін 3 | осідає за |
 *   |---------|---------:|---------:|---------:|----------:|
 *   | home    |        0 |        0 |        0 |    3–53 мс |
 *   | levels  |       16 |       16 |        5 |   15–160 мс |
 *   | profile |        1 |        2 |        2 |   15–261 мс |
 *
 * Чим це коштувало. `a11y.spec.ts` читав контраст `.action-btn.primary` при
 * `opacity` 0,65–0,73 і звітував блендовані кольори: `#ddc8c0` на `#ae411c`
 * (3,66), `#ccb6ae` на `#9d3c1a` (3,51), `#f2e2dc` на `#c8491d` (3,76) — три
 * прогони, три різні числа. Справжня пара цієї кнопки — `#ffffff` на
 * `#e95420`, 3,64. Тобто:
 *
 *   * числа у звіті не належать жодному станові сторінки й не повторюються;
 *   * вузол біля межі 4,5 зеленів і червонів випадково;
 *   * і головне — блендування зсуває відношення В ОБИДВІ СТОРОНИ. Справжнє
 *     порушення могло пройти гейт саме тому, що його заміряли при 65 %
 *     непрозорості.
 *
 * `reflow.spec.ts` мав те саме на розкладці: `BaseModal` входить через
 * `transition:scale={{ start: 0.9 }}`, а трансформований блок дає МЕНШУ
 * прокручувану область. Тобто вміст, який на 320 px вилазить убік, міряється
 * стиснутим і вкладається в межу.
 *
 * Чому очікування, а не вимкнені анімації: вимкнувши їх, ми поміряли б
 * сторінку, якої не буває. Тут вимірюється саме та, яку бачить людина, — просто
 * після того, як вона перестала рухатися.
 *
 * Чому Web Animations API, а не пауза за часом: `getAnimations()` каже про
 * СТАН, а не про «мабуть, уже досить». Свелтові переходи заводяться саме через
 * нього — це не припущення, а те, що видно в таблиці вище: 16 біжучих
 * `CSSTransition` на `levels`.
 */

/** Межа очікування. Найдовше заміряне осідання — 261 мс, тобто запас 19-кратний. */
const SETTLE_TIMEOUT = 5_000;

export async function waitForAnimationsToSettle(page: Page): Promise<void> {
	await page.waitForFunction(
		() => {
			// Без API немає й перевірки: тиха «нуль анімацій» зробила б
			// очікування декоративним, а гейт — знову недетермінованим.
			if (typeof document.getAnimations !== "function")
				throw new Error("document.getAnimations() немає — осідання не перевіряється");
			return document.getAnimations().every((a) => a.playState !== "running");
		},
		null,
		{ timeout: SETTLE_TIMEOUT },
	);
}
