import { defineConfig, devices } from '@playwright/test';

/**
 * Окремий порт саме для тестів, і свій у кожному проєкті.
 *
 * Було `5173` плюс `reuseExistingServer: !process.env.CI`. Локально це означало:
 * якщо на 5173 уже висить dev-сервер ІНШОГО проєкту (а 5173 — типовий порт
 * Vite, тобто в усіх сімох він той самий), Playwright спокійно бере його й
 * перевіряє чужий застосунок. Тест зелений, перевірено не те — рівно клас
 * AI-AGENT-PITFALLS-v8 § 1. Саме так і сталося: інваріант унікальності
 * `data-testid` проходив, дивлячись на сусідній сайт.
 */
const TEST_PORT = 5273;

/**
 * `baseURL` мусить враховувати `base` зі `svelte.config.js` (CODE-QUALITY-v8
 * § 5.4). Тут `base` — `/Slovko`, тож без нього `page.goto('/')` веде на адресу,
 * якої в застосунку немає. Досі це працювало лише тому, що Vite сам
 * перенаправляє корінь на базовий шлях — тобто перевірки трималися на
 * поведінці dev-сервера, а не на власній адресації.
 *
 * Наслідок для тестів: шляхи в них РЕЛЯТИВНІ (`''`, `'?modal=levels'`).
 * Провідний слеш у `new URL(path, baseURL)` відкидає базовий шлях цілком.
 */
const BASE_PATH = process.env.BASE_PATH ?? '/Slovko';

export default defineConfig({
	testDir: './tests/e2e',
	fullyParallel: true,
	forbidOnly: !!process.env.CI,
	retries: process.env.CI ? 2 : 0,
	workers: process.env.CI ? 1 : undefined,
	reporter: 'html',
	use: {
		trace: 'on-first-retry',
		baseURL: `http://localhost:${TEST_PORT}${BASE_PATH}/`,
	},
	projects: [
		{
			name: 'chromium',
			/*
			 * Локаль задана явно (CODE-QUALITY-v8 § 5.7).
			 *
			 * Playwright типово ставить `en-US`, а `i18n/init.ts` бере початкову
			 * мову з `getLocaleFromNavigator()`. Тобто ВЕСЬ E2E досі ходив по
			 * англійській версії — не по тій, яку бачить типовий відвідувач, і не
			 * по тій, що стоїть у `<html lang="uk">` збірки. Порушення, яке живе
			 * лише в українських рядках (обрізаний підпис, зайвий пробіл,
			 * відсутній переклад), не мало жодного шансу трапитися.
			 */
			use: { ...devices['Desktop Chrome'], locale: 'uk-UA' },
		}
	],
	webServer: {
		/*
		 * Прев'ю ЗІБРАНОГО сайту, а не `vite dev` (CODE-QUALITY-v8 § 5.7).
		 *
		 * Доти тут стояв `npm run dev`, і це означало, що весь E2E перевіряв
		 * інший застосунок, ніж той, що їде на хостинг. Різниця не косметична —
		 * вона рівно в тих місцях, де живуть дефекти:
		 *
		 *   • CSP. У dev політика приходить ЗАГОЛОВКОМ із nonce, у збірці —
		 *     мета-тегом із хешами. Це дві різні політики, і асерт
		 *     `smoke.spec.ts` про «CSP нічого не заблокувала» перевіряв ту, якої
		 *     на хостингу немає. Хеш, що розійшовся з `app.html`, блокує скрипт
		 *     МОВЧКИ — і саме цей випадок був невидимий.
		 *   • Порядок CSS. У dev стилі компонентів інжектяться скриптом ПІСЛЯ
		 *     `app.css`, у збірці — окремим `<link>` перед ним. При рівній
		 *     специфічності виграє РІЗНЕ правило (SVELTE-UI-v8 § 3.6).
		 *   • Розмітка. Пререндер-HTML із диску проти рендера на запит: порожнє
		 *     тіло, canonical і `sveltekit-prerender` в адресах у dev не
		 *     відтворюються взагалі (SEO-v8 § 1).
		 *
		 * Збірка стоїть у самій команді, а не окремим кроком, навмисно: прев'ю
		 * над старою збіркою — це та сама пастка, тільки тихіша (падіння
		 * виглядає як регресія у свіжому коді). Ціна — ~30 c на прогін.
		 *
		 * `--strictPort`: якщо порт зайнятий, Vite мусить УПАСТИ, а не тихо
		 * перейти на наступний. Інакше Playwright перевіряв би сайт за адресою,
		 * яку зайняв хтось інший.
		 */
		command: `npm run build && npx vite preview --port ${TEST_PORT} --strictPort`,
		/*
		 * З базовим шляхом, а не голий корінь: `vite preview` віддає на `/`
		 * рівно 404, а Playwright вважає сервер готовим лише на код < 400 —
		 * тобто чекав би до таймауту й падав на цілком робочому сервері.
		 */
		url: `http://localhost:${TEST_PORT}${BASE_PATH}/`,
		// Ніколи не перевикористовуємо чужий сервер — див. коментар до TEST_PORT.
		reuseExistingServer: false,
		// Збірка + підйом прев'ю не вкладаються в типові 60 c.
		timeout: 240_000,
	},
});