import { fileURLToPath } from "node:url";
import { defineConfig } from "vitest/config";
import { svelte } from "@sveltejs/vite-plugin-svelte";

export default defineConfig({
	plugins: [svelte({ hot: !process.env.VITEST })],
	resolve: {
		alias: {
			// Псевдонім `$lib` дає SvelteKit, а не Vite, — і під vitest його
			// немає. Доти це не заважало лише тому, що єдиний тест, який тягнув
			// `$lib`, той модуль ще й підміняв через `vi.mock`: підміна
			// перехоплює специфікатор і до резолву справа не доходить. Перший же
			// СПРАВЖНІЙ імпорт по `$lib` падав із «Cannot find module».
			$lib: fileURLToPath(new URL("./src/lib", import.meta.url)),
		},
	},
	test: {
		include: ["src/**/*.{test,spec}.{js,ts}"],
		// `node`, а не `jsdom`: пакета `jsdom` у проєкті немає, і через це
		// `pluralize.test.ts` не запускався зовсім — vitest не міг підняти для
		// нього воркер. Два інші файли це обходили докблоком
		// `// @vitest-environment node`, третій — ні, і його падіння виглядало
		// як «2 passed» плюс окремий рядок про помилку.
		//
		// Жодному з наявних тестів DOM не потрібен. Якщо колись знадобиться —
		// поставити `jsdom` у devDependencies і закріпити середовище саме в
		// тому файлі докблоком, а не глобально.
		environment: "node",
		globals: true,
		/*
		 * Межа часу на тест — 30 с замість типових 5 (AI-AGENT-PITFALLS § 1.4:
		 * гейт, який червоніє не від дефекту, перестає бути гейтом).
		 *
		 * Майже кожен інваріант тут проходить УСЕ дерево джерел: 1155 файлів,
		 * і в найгіршому разі читає кожен. Власної роботи в такому тесті
		 * 100–400 мс, але воркери vitest — окремі процеси, і всі вони
		 * впираються в один диск одночасно. Розтяг у такій черзі не
		 * пропорційний: у прогоні 2026-09-10 `test-runners.test.ts` показав
		 * 5263 мс на тесті, який поодинці робиться за 171 мс, — тридцятикратно,
		 * тобто рівно повз типові 5000. Результат був `1 failed | 39 passed`
		 * із причиною «Test timed out», хоча жодного порушення не було.
		 *
		 * Ціна такого падіння вища за втрачений прогін: `test:unit` — найбільший
		 * гейт цього пайплайну, і випадкове червоне на ньому вчить перезапускати
		 * замість читати. Саме так гейти й перестають щось означати.
		 *
		 * 30 с — це 75 разів від найповільнішого тесту проєкту (401 мс,
		 * `hooks.client.test.ts`) і майже шість разів від найгіршого
		 * заміряного розтягу. Справжнє зависання (нескінченний цикл, обіцянка,
		 * яка не розв'язується) ловиться так само, лише на пів хвилини пізніше.
		 */
		testTimeout: 30_000,
		hookTimeout: 30_000,
	},
});
