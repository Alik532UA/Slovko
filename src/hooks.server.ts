import type { Handle } from "@sveltejs/kit";
import { isHiddenRoute } from "$lib/config/hiddenRoutes";

/**
 * Прибирає `canonical` зі сторінок, яких не мусить бути в пошуку
 * (BETA-CHECKLIST-v8 § 4).
 *
 * Чому не просто «не малювати його там»: `canonical` у цьому проєкті лежить
 * СТАТИЧНО в `app.html`, а не в `<svelte:head>`. Так вийшло не від недбалості —
 * ігровий маршрут вимикає SSR (гра залежить від сховища браузера), і все з
 * `svelte:head` до пререндереного HTML не доїжджає взагалі: сторінка виходила
 * без заголовка й показувалася в пошуку голою адресою. Статичний блок у
 * `app.html` — єдина частина `<head>`, що переживає `ssr = false`, і саме тому
 * він однаковий для ВСІХ сторінок.
 *
 * Хук — місце, де це можна розрізнити: у статичному профілі він виконується
 * під час пререндеру, тобто правка потрапляє в зібраний файл, а не робиться
 * після збірки скриптом, який шукає рядок і мовчки нічого не знаходить.
 *
 * Чому взагалі без `canonical`: разом із `noindex` він дає протилежні сигнали —
 * «не індексуй» і «оце канонічна адреса для індексу». Перевіряє обидві
 * обіцянки `scripts/check-build.mjs`, і для решти сторінок — ПРОТИЛЕЖНЕ.
 */
export const handle: Handle = async ({ event, resolve }) => {
	if (!isHiddenRoute(event.url.pathname)) return resolve(event);

	return resolve(event, {
		transformPageChunk: ({ html }) =>
			html.replace(/\s*<link rel="canonical"[^>]*>/g, ""),
	});
};
