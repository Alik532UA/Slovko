import { base } from '$app/paths';
import { json } from '@sveltejs/kit';

/**
 * МАНІФЕСТ PWA — виводиться з `base`, а не лежить статичним файлом.
 *
 * ## Що було не так
 *
 * `static/manifest.json` зашивав `"/Slovko/"` у `scope` і `start_url`.
 * Базовий шлях при цьому живе в `svelte.config.js` (`process.env.BASE_PATH ??
 * "/Slovko"`), тобто одне й те саме число існувало у ДВОХ місцях, і друге про
 * перше не знало.
 *
 * Ціна розбіжності не «неохайно». `scope` вирішує, які адреси належать
 * встановленому застосунку: якщо він не збігається зі справжнім шляхом,
 * встановлений застосунок відкриває сторінку в звичайній вкладці браузера —
 * тобто встановлення просто перестає щось означати. Помітити це можна лише
 * встановивши застосунок, і жоден гейт по коду цього не бачив би.
 *
 * Сусідні `AudioRemote` і `MindStep` виводять маніфест із `BASE_PATH` уже
 * давно — там це робить `vite-plugin-pwa`. Тут плагіна немає (воркер власний),
 * тож маніфест віддає пререндерений маршрут: та сама єдина точка правди, лише
 * іншим шляхом.
 *
 * ## Чому маршрут, а не генерація файлу скриптом
 *
 * Скрипт довелося б тримати в ланцюжку `build` поруч із `generate-sitemap`, і
 * він читав би `BASE_PATH` із власного `process.env` — тобто третє місце, де
 * те саме значення можна помилитися. Маршрут бере `base` із `$app/paths`,
 * тобто рівно те, з чим SvelteKit зібрав решту сторінок.
 *
 * Пререндер обовʼязковий: адаптер статичний, сервера в продакшні немає.
 */
export const prerender = true;

/**
 * Один префікс на всі адреси всередині маніфеста.
 *
 * `base` — це шлях БЕЗ кінцевого слеша (`/Slovko`), а `scope` і `start_url`
 * його потребують: `/Slovko` без слеша охоплює ще й `/Slovko2`, якби такий
 * колись з'явився на сусідньому шляху.
 */
const scope = `${base}/`;

export function GET() {
	return json({
		name: 'Slovko',
		short_name: 'Slovko',
		description: 'Easy and fun language learning by matching word pairs',
		id: scope,
		start_url: scope,
		scope,
		display: 'standalone',
		background_color: '#23272f',
		theme_color: '#e95420',
		orientation: 'portrait-primary',
		lang: 'uk',
		categories: ['education', 'games'],
		/*
		 * `any`, а не `any maskable` — заміряно декодуванням PNG (числа й
		 * причина в `PROJECT-CONTEXT.md`). Коротко: тло тут суцільне, але
		 * логотип «IQ» виходить за поле безпеки (радіус вмісту 118.1 при 76.8
		 * для 192 px), тож під круглою маскою хвіст «Q» обрізало б.
		 *
		 * Адреси значків теж із `base`: відносні (`./icon-192.png`) тут
		 * працювали б, бо маніфест лежить у корені застосунку, — але вони
		 * резолвляться проти адреси МАНІФЕСТА, і будь-який переїзд цього
		 * маршруту глибше тихо зламав би їх.
		 */
		icons: [
			{
				src: `${scope}icon-192.png`,
				sizes: '192x192',
				type: 'image/png',
				purpose: 'any'
			},
			{
				src: `${scope}icon-512.png`,
				sizes: '512x512',
				type: 'image/png',
				purpose: 'any'
			}
		]
	});
}
