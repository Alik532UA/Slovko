/**
 * Чи можна вже кликати `$_` — для екранів, які показуються, КОЛИ ЗЛАМАЛОСЯ.
 *
 * Звичайний екран цього питання не має: макет не малює застосунок, доки
 * словник не приїхав, тож усередині нього `$_` безпечний завжди. Аварійні
 * екрани — заставка застряглого старту, `+error.svelte`, `ErrorBoundary` —
 * малюються саме тоді, коли гарантії немає, і зокрема тоді, коли не приїхав
 * саме словник.
 *
 * ## Чому НЕ `!$isLoading`
 *
 * Здається очевидним, що «не завантажується» означає «завантажено». Це не так,
 * і перевірено це не міркуванням, а джерелами
 * (`node_modules/svelte-i18n/dist/runtime.cjs`):
 *
 *   * `isLoading` створюється як `writable(false)` і стає `true` ЛИШЕ на час
 *     самого завантаження. Тобто до `init()` він `false` — «ще не починали» й
 *     «уже готово» виглядають однаково;
 *   * `formatMessage` при `locale == null` КИДАЄ
 *     («Cannot format a message without first setting the initial locale»).
 *
 * Разом це означає, що аварійний екран під охороною `!$isLoading` кинув би
 * рівно в тому випадку, заради якого існує, — і замість повідомлення про
 * поломку сторінка стала б порожньою. Заміряно на живому застосунку: при
 * примусовій відмові `initializeI18n()` діагностика показала
 * `i18nLoading: false` при незаданій мові.
 *
 * `locale` натомість стає непорожнім лише після того, як словник доїхав, — це
 * робить `internalLocale.set(newLocale)` у `.then()` завантаження.
 *
 * Обидві умови разом, а не одна: `locale` відповідає на «чи є чим
 * форматувати», `isLoading` — на «чи не міняється воно просто зараз».
 */
export function dictionaryReady(
	currentLocale: string | null | undefined,
	loading: boolean,
): boolean {
	return Boolean(currentLocale) && !loading;
}
