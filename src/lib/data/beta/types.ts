/**
 * Дві мови в ОДНОМУ об'єкті, а не двома деревами файлів.
 *
 * Відповідність вимагає ТИП: пункт без англійського тексту не збереться. Двома
 * деревами вона потребувала б окремого правила про однакові `id`, однаковий
 * порядок і однакову кількість — і окремого скрипта, який це звіряє.
 *
 * Тексти пунктів НЕ живуть у словнику інтерфейсу: їх десятки, вони змінюються
 * іншим циклом, і паритет семи мов зробив би кожну правку семикратною. Решта
 * мов бачить англійський текст.
 */
export interface Localized {
	uk: string;
	en: string;
}

/**
 * Чи може це перевірити машина.
 *
 * Порядок показу саме такий, і це не косметика:
 * - `manual` — людина витрачається спершу там, де машини немає;
 * - `testable` — готовий БЕКЛОГ тестів: не «треба більше тестів», а перелік;
 * - `covered` — контрольна група. Помилка, знайдена тут, — це звіт про дефект
 *   ТЕСТА, а не застосунку, і вона знецінює всі зелені прогони.
 */
export type Coverage = "manual" | "testable" | "covered";

export interface BetaCheck {
	/**
	 * Стабільний НАЗАВЖДИ: у ньому лежить прогрес людини. Перейменувати
	 * `game_7` означає стерти комусь позначку. Нові пункти дописуються з новим
	 * номером; перенумеровувати наявні не можна навіть тоді, коли змінився
	 * порядок. Номер, який видно на екрані, малює сторінка з позиції.
	 */
	id: string;
	category: Localized;
	text: Localized;
	coverage: Coverage;
	/** Обов'язковий для `covered`, заборонений для решти. Шлях від кореня. */
	test?: string;
	/** Обов'язковий там, де в тексті є «натисніть» — інакше пункт неперевірний. */
	testid?: string;
	/** Перевірка МЕЖІ: «не мусить». Найдорожчі дефекти тихі. */
	negative?: true;
}

export interface BetaTab {
	id: string;
	title: Localized;
	/** Стани застосунку з `config/appStates.ts`, які заявляє ця вкладка. */
	states: readonly string[];
	checks: readonly BetaCheck[];
}

/** Чотири стани відповіді, а не два. */
export type Vote = "fail" | "weird" | "ok";

export interface Mark {
	vote: Vote;
	/**
	 * Версія збірки, на якій поставили. Позначка з іншої версії не зникає —
	 * вона все ще щось означає, — але підписана й НЕ рахується в «зроблено на
	 * цій». Без цього список поступово стає звітом про минуле, який читають як
	 * звіт про теперішнє.
	 */
	version: string;
}

/** Порядок показу рівнів покриття. Змінювати не можна — див. `Coverage`. */
export const COVERAGE_ORDER: readonly Coverage[] = ["manual", "testable", "covered"];
