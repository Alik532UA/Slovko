/**
 * Що варто повторювати, а що ні (ERROR-HANDLING-v8 § 3.1).
 *
 * Окремий чистий модуль, а не рядок усередині `SyncService.svelte.ts`: там
 * поруч лежить SDK, і перевірка цього рішення вимагала б бойових ключів, щоб
 * узагалі зібратися. Тут — жодного імпорту, тож правило перевіряється
 * звичайним юніт-тестом.
 */

/**
 * Коди Firestore, на яких повтор безглуздий.
 *
 * Повторювати варто мережеві збої й тимчасову недоступність. Відмова правил
 * доступу, відсутній сеанс і неприйнятні дані — це відповідь «ні», яка не
 * стане «так» від очікування: три спроби з наростаючою паузою лише
 * відкладають той самий `status = "error"` на сім секунд, тримаючи весь цей
 * час індикатор синхронізації в стані, який ні на що не перетвориться.
 *
 * Найважливіший тут `permission-denied`. `SyncService` уже вмів його
 * відрізняти — рівнем логування, — але однаково ставив у чергу на повтор. А
 * приходить він саме тоді, коли в правилах бракує шляху, тобто рівно тоді,
 * коли повтор шкодить найбільше: ховає прогалину за трьома тихими спробами.
 */
export const NON_RETRYABLE_CODES = new Set([
	"permission-denied",
	"unauthenticated",
	"invalid-argument",
	"failed-precondition",
	"not-found",
]);

/**
 * Невідоме вважається таким, що можна повторити.
 *
 * Помилка без `code` — це майже завжди збій транспорту, і саме заради нього
 * повтор існує. Протилежне типове значення означало б, що перша ж незнайома
 * форма помилки тихо вимикає синхронізацію.
 */
export function isRetryable(error: unknown): boolean {
	const code = (error as { code?: unknown } | null | undefined)?.code;
	return typeof code === "string" ? !NON_RETRYABLE_CODES.has(code) : true;
}
