<script lang="ts">
	/**
	 * Structured Data — розмітка Schema.org для пошуковиків і AI-краулерів
	 * (SEO-v8 § 3.2, § 7.4).
	 *
	 * **Чому окремий компонент, а не рядок у layout.** JSON-LD віддається через
	 * `{@html}` — інакше ніяк: вирази всередині `<script>` у розмітці Svelte не
	 * обчислюються (SEO-v8 § 3.2). А `svelte/no-at-html-tags` у цьому проєкті
	 * має рівень `error`, і придушується він ФАЙЛОВИМ винятком, а не
	 * коментарем: така конвенція записана в `eslint.config.js` над винятком для
	 * `SpeechErrorModal.svelte`. Спроба обійтися
	 * `<!-- eslint-disable-next-line -->` просто в layout не спрацювала —
	 * `eslint-plugin-svelte` 3.15 директив у HTML-коментарях розмітки не читає
	 * (у CV з 3.20 читає, тому там такий коментар і працює). Файловий виняток
	 * від версії плагіна не залежить.
	 *
	 * Вміст тут — НЕ користувацький ввід: об'єкт збирається в layout з констант
	 * і зі значення мови інтерфейсу з переліку підтримуваних. `JSON.stringify`
	 * екранує лапки й керівні символи, тож у `<script>` не потрапляє нічого,
	 * що могло б його закрити.
	 */
	let { data }: { data: unknown } = $props();
</script>

<!--
	`JSON.stringify` стоїть УСЕРЕДИНІ `{@html}`, а не в проміжній змінній, і це
	не стиль: `security.test.ts` § 5 шукає ознаку санітизації в самому виразі
	`{@html …}`. Винесення у `$derived tag` ховає гарантію від перевірки — і
	перевірка падає, як і має падати, бо з місця використання вже не видно,
	чи оброблене значення.

	`</` + `script>` замість `<\/script>`: екран у шаблонному рядку зайвий, і
	`no-useless-escape` ловить його як помилку — саме на цьому впав
	VetCrewGames. Розрив рядка дає те саме, що давав би екран: у джерелі немає
	послідовності, яку парсер міг би прийняти за кінець тега.
-->
<svelte:head>
	{@html `<script type="application/ld+json">${JSON.stringify(data)}</` +
		`script>`}
</svelte:head>
