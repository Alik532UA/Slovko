<script lang="ts">
	import type { Snippet } from "svelte";

	/**
	 * КАРТКА ДЛЯ ГОСТЯ: значок ЛІВОРУЧ, текст праворуч.
	 *
	 * ## Що було не так
	 *
	 * Значок стояв над текстом, і картка через це займала три рядки заввишки —
	 * над самою формою входу, тобто відсувала вниз те, по що людина прийшла.
	 * Автор сказав це прямо: «актуальний результат — зверху лого, знизу текст;
	 * очікуваний — ліворуч лого, праворуч текст».
	 *
	 * Рядком вона займає одну висоту тексту, а значок робить те, для чого він тут і
	 * є: позначає рід повідомлення, не претендуючи на місце.
	 *
	 * ## Чому окремий компонент на дев'ять рядків розмітки
	 *
	 * Бо їх було ДВА: однакова картка з однаковими стилями лежала копією в
	 * `ProfileModal` і в `StatsModal`, і саме тому вигляд там уже почав
	 * розходитися — розмір значка той самий, а відступи задавав інлайновий
	 * `style="margin-bottom: 1rem"` у кожному місці окремо. Одна копія — одне
	 * рішення; наступне «ліворуч чи згори» правиться в одному файлі.
	 */
	interface Props {
		/** Значок роду повідомлення: попередження, кубок, замок. */
		icon: Snippet;
		/** Текст. Рядок, а не сніпет: усередині ніколи не буває розмітки. */
		text: string;
	}

	let { icon, text }: Props = $props();
</script>

<div class="guest-warning-box" data-testid="guest-warning">
	<div class="warning-icon" aria-hidden="true">{@render icon()}</div>
	<p>{text}</p>
</div>

<style>
	/*
	 * РЯДОК, а не стовпець. `align-items: center` вирівнює значок по центру
	 * тексту, а не по його першому рядку: у два рядки текст тут буває на вузькому
	 * екрані, і значок, притиснутий до верху, читався б як щось окреме над ним.
	 */
	.guest-warning-box {
		display: flex;
		align-items: center;
		gap: 0.75rem;
		margin-bottom: 1rem;
		padding: 1rem 1.25rem;
		background: rgba(241, 196, 15, 0.05);
		border-radius: 20px;
		border: 1px dashed rgba(241, 196, 15, 0.2);
		color: var(--text-secondary);
		text-align: start;
	}

	/*
	 * Значок не стискається: без цього flex забирає місце саме в нього — текст
	 * довший, тож він виграє, і значок сплющується в овал.
	 */
	.warning-icon {
		display: flex;
		flex-shrink: 0;
		align-items: center;
		color: #f1c40f;
		opacity: 0.8;
	}

	.guest-warning-box p {
		margin: 0;
	}
</style>
