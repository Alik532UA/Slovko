// @vitest-environment node
import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Покриття локалізації: ключі без ужитку й підписи без перекладу.
 *
 * Обидві перевірки — про одне й те саме правило «наявність ≠ використання»
 * (PROJECT-STRUCTURE-v8 § 4.3, який окремо називає ключі локалізації), тільки з
 * різних боків:
 *
 * 1. Ключ є у ВСІХ семи словниках і ним не користується жоден рядок коду. Саме
 *    так шістнадцять перекладених повідомлень про помилки входу простояли без
 *    ужитку, доки форма показувала англійський текст Firebase. Паритет ключів
 *    (`translations.test.ts`) цього не бачить: він звіряє словники між собою, а
 *    не з кодом, тож мертвий ключ у ньому — рівно такий самий «OK».
 *
 * 2. Підпис для читалки написано просто рядком. Для незрячого відвідувача це
 *    англійський напис посеред інтерфейсу однією з семи мов. Гейт кнопок
 *    закриття вже вимагає підпис із i18n — але лише для них.
 *
 * Обидва переліки МОЖУТЬ ЛИШЕ СКОРОЧУВАТИСЯ. Число, а не `toEqual([])`, — бо
 * порожній перелік довелося б купувати або видаленням тексту, продуктовий сенс
 * якого не перевіриш читанням коду, або вигаданим перекладом грецькою й
 * кримськотатарською. І те, і те гірше за названу цифру.
 */

const ROOT = process.cwd();
const SRC = join(ROOT, "src");
const DICT = join(SRC, "lib/i18n/translations/uk.json");

/**
 * Ключі, що пережили свій екран: текст лишився від попередніх версій
 * онбордингу, меню й налаштувань, які тепер беруть інші ключі
 * (`onboarding.step1_part1…` замість `explanationPart1…`,
 * `settings.columnLeft/columnRight` замість `settings.from/to`,
 * `about.title`/`about.support` замість `menu.about`/`menu.donate`).
 *
 * 21 → 20: `profile.anonymousTitle` («Гість») ожив — саме він тепер стоїть у
 * шапці профілю замість англійського рядка `"User"`, зашитого в розмітку.
 *
 * Не видалено одним рухом навмисно: кожен рядок — це сім перекладів, і рішення
 * «цей екран більше не повернеться» приймає власник продукту, а не аудит.
 * Число тут — стеля, яку можна лише знижувати.
 */
const KNOWN_UNUSED_KEYS = 20;

/**
 * Підписи для читалки, написані рядком. Сім із них закрито 2026-08-19 за
 * рахунок ключів, що вже існували (`common.listen`, `common.save`,
 * `common.edit`, `common.cancel`, `common.copyReport`,
 * `playlists.addCustomWord`), ще один — 15 → 14 — полем імені в шапці профілю
 * (`profile.nameLabel`).
 *
 * **14 → 1.** Решта закрита групою `a11y.*` — тринадцять ключів у всіх семи
 * мовах. Доти тут стояло, що вигадувати їх наосліп означало б тихо погіршити
 * чесно англійське; це правда для тексту, сенс якого видно лише на екрані, і
 * неправда для «Move up», «Delete» чи «Online». Заразом два підписи стали
 * кращими за оригінал: `Flag {lang}` вимовлявся як «Прапор nl» і тепер бере
 * назву мови, а `Step {i + 1}` став параметризованим ключем.
 *
 * Група окрема (`a11y`), а не розкидана по екранах, бо ці рядки об'єднує не
 * екран, а призначення: на екрані їх немає взагалі, тож знайти їх інакше
 * неможливо.
 *
 * Той, що лишився, — `ThreadsIcon`: власна назва сервісу. Читалка вимовляє
 * «Threads» правильно будь-якою мовою, і перекладати тут нічого. Нуля
 * перевірка не вимагає саме тому, що такі випадки бувають.
 */
const KNOWN_HARDCODED_LABELS = 1;

function walk(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) walk(full, out);
		else if (/\.(ts|js|svelte)$/.test(entry)) out.push(full.replace(/\\/g, "/"));
	}
	return out;
}

function flatten(value: unknown, prefix = ""): string[] {
	if (value === null || typeof value !== "object" || Array.isArray(value))
		return [prefix];
	return Object.entries(value as Record<string, unknown>).flatMap(([k, v]) =>
		flatten(v, prefix ? `${prefix}.${k}` : k),
	);
}

/*
 * Файли перевірок виключені навмисно. Інакше згадка ключа в коментарі — навіть
 * у коментарі САМЕ ЦІЄЇ перевірки, який пояснює, чому ключ мертвий, — робить
 * його «вжитим», і гейт починає рахувати власний текст за код. Так і сталося
 * під час написання: перелік мовчки скоротився на два.
 */
const files = walk(SRC).filter((f) => !/\.(test|spec)\.(ts|js)$/.test(f));
const sources = files.map((f) => readFileSync(f, "utf8")).join("\n");
const keys = flatten(JSON.parse(readFileSync(DICT, "utf-8")));

/**
 * Гілки, які збираються в рантаймі: `$_(\`levels.${id}\`)` робить ужитими всі
 * ключі під `levels.`. Без цього перевірка оголосила б мертвими рівні, теми,
 * часи й теми оформлення — тобто сварилася б на цілком робочий код.
 */
const dynamicPrefixes = [
	...new Set([...sources.matchAll(/["'`]([\w.]*?)\$\{/g)].map((m) => m[1])),
].filter(Boolean);

const unusedKeys = keys
	.filter((k) => !sources.includes(k))
	.filter((k) => !dynamicPrefixes.some((p) => k.startsWith(p)));

/**
 * Розмітка компонента без HTML-коментарів.
 *
 * Прибирати їх обов'язково, і причина знайшлася прогоном: коментар, який
 * ПОЯСНЮЄ, чому з елемента прибрано `aria-label`, сам містить цей рядок — і
 * гейт рахував пояснення за порушення. Той самий клас, що вже описаний вище
 * для мертвих ключів («гейт починає рахувати власний текст за код»), тільки з
 * протилежним знаком: там коментар ховав дефект, тут — вигадував його.
 *
 * Довжина рядків зберігається (символи замінюються пробілами), щоб номери
 * рядків у звіті лишалися справжніми.
 */
const withoutComments = (text: string): string =>
	text.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, " "));

const hardcodedLabels = files
	.filter((f) => f.endsWith(".svelte"))
	.flatMap((f) =>
		[
			...withoutComments(readFileSync(f, "utf8")).matchAll(
				/aria-label="([^"{][^"]*)"/g,
			),
		].map((m) => `${f.replace(`${ROOT.replace(/\\/g, "/")}/`, "")}: ${m[1]}`),
	);

/**
 * Ключ, ужитий у коді й відсутній у словниках, — дзеркальний бік того самого
 * правила, і саме він видний ВІДВІДУВАЧЕВІ.
 *
 * `svelte-i18n` на відсутньому ключі не падає й не віддає порожнього рядка. Він
 * повертає САМ ІДЕНТИФІКАТОР (`runtime`: `handleMissingMessage() ?? default ??
 * id`), тобто на екран іде `common.navigation`, а диктор читає це вголос. Усіма
 * сімома мовами одразу, бо ключа немає в жодній.
 *
 * Прогін на момент появи знайшов чотирнадцять таких ключів, і шість із них
 * бачив користувач: `common.navigation` (підпис нижньої панелі для читалки),
 * `interaction.title` і `settings.languageSettings` (ще два підписи),
 * `playlists.clipboardEmpty` (текст попередження), `profile.confirmLogout`
 * (питання у вікні підтвердження виходу) і `about.feedback.instruction`
 * (єдиний, що мав `default:` і показував українську всім мовам).
 *
 * Чому це прожило непоміченим — головне в цій знахідці. Поруч із кожним стояв
 * запас: `$_('common.navigation') || "Level navigation"`. Він НЕ ПРАЦЮЄ НІКОЛИ:
 * `$_` віддає ідентифікатор, ідентифікатор — непорожній рядок, `||` бере перше
 * значення. Тобто код виглядав захищеним рівно там, де був зламаний, і
 * захардкоджений текст поруч читався як «тут усе передбачено».
 *
 * Решта вісім — `auth.*` у формі входу, у тій самій недосяжній позиції:
 * `$_('profile.signinTitle') || $_('auth.title')`. Простояли, поки перша
 * половина працювала.
 *
 * `toEqual([])`, а не число: тут немає продуктового вибору, який довелося б
 * купувати вигаданим перекладом. Ключ або є у словниках, або код показує
 * ідентифікатор. Це відрізняє цю перевірку від двох переліків вище.
 *
 * Зворотний експеримент виконано: перейменований `a11y.levelNavigation` у
 * `BottomBar.svelte` — червоне з іменем файлу.
 */

/**
 * Літерал ЦІЛКОМ і одразу закритий: `[),]` після нього.
 *
 * Без цієї межі `$_('levels.' + id)` дав би «ключ `levels.`», якого справді
 * немає в словнику, — тобто перевірка сварилася б на робочий код. Ключі, що
 * збираються в рантаймі, лишаються за `dynamicPrefixes` вище: перевірити їх
 * читанням джерела неможливо.
 */
const LITERAL_KEY = /\$?_\(\s*(['"])([\w.]+)\1\s*[),]/g;

const referencedKeys: { key: string; file: string }[] = [];
const seenReference = new Set<string>();
for (const file of files) {
	const short = file.replace(`${ROOT.replace(/\\/g, "/")}/`, "");
	for (const m of withoutComments(readFileSync(file, "utf8")).matchAll(LITERAL_KEY)) {
		const mark = `${short} ${m[2]}`;
		if (seenReference.has(mark)) continue;
		seenReference.add(mark);
		referencedKeys.push({ key: m[2], file: short });
	}
}

describe("покриття локалізації", () => {
	it("перевірка жива: ключі, джерела й динамічні гілки знайдено", () => {
		expect(keys.length).toBeGreaterThan(300);
		expect(files.length).toBeGreaterThan(50);
		// Порожній перелік префіксів означав би, що розбір шаблонних рядків
		// зламався, і перевірка почала б рахувати робочі ключі за мертві.
		expect(dynamicPrefixes.length).toBeGreaterThan(0);
	});

	it("розбір лишає розмітку й прибирає коментарі", () => {
		// Канарка на `withoutComments`: помилка в ньому робить перевірку нижче
		// сліпою МОВЧКИ — вирізаний зайвий шматок означає нуль знахідок, а
		// такий нуль читається як «усі підписи перекладені».
		const sample = withoutComments(
			['<!-- тут було aria-label="Закрити" -->', '<i aria-label="Live"></i>'].join("\n"),
		);
		expect(sample.includes('aria-label="Live"'), "розмітка мусить лишитися").toBe(true);
		expect(sample.includes('aria-label="Закрити"'), "коментар мусить зникнути").toBe(false);
		expect(sample.split("\n").length, "номери рядків мусять лишитися").toBe(2);
	});

	/*
	 * РІВНІСТЬ, а не «не більше», в обох перевірках нижче.
	 *
	 * «Не більше» ловить зростання й пропускає застарівання: ключ ожив, число
	 * лишилося старим — і наступний читач бачить борг, якого немає. Обидва
	 * числа тут звіряються ще й `docs-numbers.test.ts` із таблицею в
	 * `PROJECT-CONTEXT.md`, тобто застаріле число тихо робить неправдивими
	 * ДВА документи. Той самий аргумент, що для боргу `warn` в
	 * `eslint-baseline.test.ts`, де рівність стоїть від початку.
	 */
	it(`ключів без ужитку рівно ${KNOWN_UNUSED_KEYS}`, () => {
		expect(
			unusedKeys.length,
			"перелік може лише скорочуватися — і число опускається ТИМ САМИМ " +
				`комітом;\nзараз:\n${unusedKeys.join("\n")}`,
		).toBe(KNOWN_UNUSED_KEYS);
	});

	it(`підписів для читалки без i18n рівно ${KNOWN_HARDCODED_LABELS}`, () => {
		expect(
			hardcodedLabels.length,
			"перелік може лише скорочуватися — і число опускається ТИМ САМИМ " +
				`комітом;\nзараз:\n${hardcodedLabels.join("\n")}`,
		).toBe(KNOWN_HARDCODED_LABELS);
	});

	it("кожен ключ із коду є у словниках", () => {
		// Порожній перелік зробив би «порушень немає» правдивим за побудовою.
		expect(
			referencedKeys.length,
			"жодного літерального ключа не знайдено — розбір зламався",
		).toBeGreaterThan(200);

		const absent = referencedKeys
			.filter(({ key }) => !keys.includes(key))
			.map(({ key, file }) => `${file}: ${key}`);

		expect(
			absent,
			"`svelte-i18n` на відсутньому ключі показує САМ ІДЕНТИФІКАТОР — і всіма " +
				"сімома мовами одразу. Запас `|| \"текст\"` поруч не спрацює: " +
				"ідентифікатор непорожній, тому `||` бере перше значення:\n  " +
				absent.join("\n  "),
		).toEqual([]);
	});
});
